"""kinds.py: writes each game's kinds of light fitting for the game to read.

For every glowing surface's kind in the survey (`light-kinds.json`) it
writes one entry into `data/lights/<game>.toml`: what the rules of
`data/lights/fittings.toml` give that kind (`propose.py`). The game cannot
work this out while it plays, because the general rules read facts of the
kind over the whole game, such as its usual size and how many of its
surfaces have a lamp of the files.

An entry names the kind (`texture`, and `on`: `room` or `placeable`). A
kind that is no lamp has `lamp = false` and nothing more. A lamp has:
- `form`: `point` (all ways), `panel` (the way it faces), `down` (a
  spotlight straight down), `strip` (along its length) or `faint`;
- `colour` (0 to 1), `reach` (metres), `strength`, and `cone` (how narrow;
  0 is all ways);
- `line = true` where the whole width of the lamp shines;
- `gather = true` where one soft light stands for all its tiny pieces;
- `off`: how far off its surface its light stands (metres), where that is
  not the usual distance;
- `lamps = "bright"` where its lamps are the bright patches of its
  texture, not the welded pieces of its mesh;
- `longest`: its pieces longer than this (metres) are no lamps;
- `tint = true` where each lamp has the colour of its own bright texels;
- `always = true` where it shines although its mesh is not set to glow;
- `grow = true` where a large lamp shines stronger than a small one;
- `dark = true` where it shines although little of its texture is bright.

A `[[fitting]]` of `fittings.toml` for a texture the survey does not list
is written as it stands. The survey misses a lamp whose texture is dim by
brightness, such as a red one.
"""
import json, os
from propose import DATA, ON, ROOT, propose

HERE = os.path.dirname(os.path.abspath(__file__))
GAMES = {'k1': 'KOTOR 1', 'tsl': 'KOTOR 2'}
FIELDS = ('colour', 'reach', 'strength', 'cone', 'line', 'gather', 'off', 'lamps', 'longest', 'tint', 'always', 'grow', 'dark')


def value(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return '[' + ', '.join(value(x) for x in v) + ']'
    return repr(float(v))


def main():
    kinds = json.load(open(os.path.join(HERE, 'light-kinds.json')))
    for game, title in GAMES.items():
        out = ['# @generated by tools/light-kinds/kinds.py from data/lights/fittings.toml and\n'
               '# the survey of `kjk light-kinds`; edit fittings.toml, never this.\n#\n'
               "# %s's kinds of light fitting, one entry each. kinds.py says what the\n# fields mean.\n" % title]
        count = 0
        for kind in sorted(kinds, key=lambda kind: (kind['group'], kind['name'])):
            if kind['game'] != game or kind['group'] not in ON:
                continue
            plan = propose(kind)
            lines = ['[[kind]]', 'texture = %s' % value(kind['name']), 'on = %s' % value(ON[kind['group']])]
            if not plan['colour']:
                lines.append('lamp = false')
            else:
                lines.append('form = %s' % value(plan['key']))
                for field in FIELDS:
                    if plan.get(field) not in (None, False):
                        lines.append('%s = %s' % (field, value(plan[field])))
            out.append('\n' + '\n'.join(lines) + '\n')
            count += 1
        surveyed = {(kind['name'], ON[kind['group']]) for kind in kinds
                    if kind['game'] == game and kind['group'] in ON}
        for entry in DATA.get('fitting', []):
            if entry['game'] != game or (entry['texture'], entry['on']) in surveyed:
                continue
            lines = ['[[kind]]', 'texture = %s' % value(entry['texture']), 'on = %s' % value(entry['on']),
                     'form = %s' % value(entry['form'])]
            lines += ['%s = %s' % (field, value(entry[field])) for field in FIELDS
                      if entry.get(field) not in (None, False)]
            out.append('\n' + '\n'.join(lines) + '\n')
            count += 1
        path = os.path.join(ROOT, 'data', 'lights', game + '.toml')
        open(path, 'w', encoding='utf-8', newline='\n').write(''.join(out))
        print(game, count, 'kinds')


if __name__ == '__main__':
    main()
