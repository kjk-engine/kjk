//! Compiles the rulebook (`data/rules/*.toml`) into Rust: each rule a
//! constant in the module its place in the book names
//! (`combat.damage.pace` → `rules::combat::damage::PACE`), and the whole
//! book, prose rendered, as `rules::BOOK` for the pages drawn from it
//! (`cargo xtask rulebook`, `kjk rules`, the game's descriptions).
//!
//! A chapter is one file: a `[chapter]` table (its `title`, `order` and
//! `summary`), then tables. A table with a `value` is a rule; any other is
//! a section, whose `title`, `summary` and `detail` head the rules and
//! sections inside it. A rule's keys:
//!
//! - `value`: a number, a boolean or an array of numbers (the constant);
//! - `type`: the element's Rust type (integers `i32` and floats `f32` when
//!   left out);
//! - `summary` (required), `detail`: what it does, in the book's words;
//! - `unit`, `labels` (an array's entries' names), `source` (where the
//!   number comes from: an executable, a reference, an owner's call),
//!   `name` (the heading, else the key's words), `range` (`[least, most]`:
//!   a value outside it fails the build), `see` (the code that applies it).
//!
//! A rule or a section may say what it `applies` to, for the pages about
//! those things (a power's description, a weapon's): tags `what:label`,
//! a row of the game's tables by its label (`spell:`, `feat:`, `skill:`,
//! `baseitem:`, `class:`) or a kind of thing (`kind:weapon`,
//! `kind:lightsaber`, `kind:grenade`, …).
//!
//! Prose names another rule's value as `{chapter.section.rule}` (an
//! array's entry `{…rule[2]}`; `{…rule:bare}` without its unit; `{{` and
//! `}}` for braces). Every name must exist, so no page can quote a number
//! the rules no longer have.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use toml_edit::{Document, Item, Table, Value};

// The build renders prose with what it shares; `said` is the pages'.
#[allow(dead_code)]
#[path = "src/shown.rs"]
mod shown;
use shown::with_unit;

const INTEGERS: [&str; 10] = [
    "i8", "i16", "i32", "i64", "u8", "u16", "u32", "u64", "usize", "isize",
];
const FLOATS: [&str; 2] = ["f32", "f64"];
const SECTION_KEYS: [&str; 4] = ["title", "summary", "detail", "applies"];
const RULE_KEYS: [&str; 11] = [
    "value", "type", "summary", "detail", "unit", "labels", "source", "name", "range", "see",
    "applies",
];
/// What an `applies` tag may name: a row of the game's tables by its
/// label (`spell:FORCE_POWER_FORCE_PUSH`), or a kind of thing (`weapon`).
const APPLIES: [&str; 6] = ["spell", "feat", "skill", "baseitem", "class", "kind"];

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/rules");
    println!("cargo:rerun-if-changed={}", root.display());
    let mut files: Vec<PathBuf> = std::fs::read_dir(&root)
        .unwrap_or_else(|error| panic!("{}: {error}", root.display()))
        .map(|entry| entry.expect("a rulebook entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "toml"))
        .collect();
    files.sort();
    let mut chapters = Vec::new();
    for path in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(path).expect("a rulebook file");
        // Parsed keeping its spans: each number is read as written.
        let doc = Document::parse(text.as_str())
            .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        let stem = path.file_stem().and_then(|s| s.to_str()).expect("a name");
        chapters.push(
            read_chapter(stem, doc.as_table(), &text).unwrap_or_else(|error| {
                panic!("{}: {error}", path.display());
            }),
        );
    }
    chapters.sort_by_key(|chapter| (chapter.order, chapter.key.clone()));
    let values = values(&chapters);
    let mut errors = Vec::new();
    let mut rust =
        String::from("// @generated by crates/rules/build.rs from data/rules/*.toml.\n\n");
    let mut book =
        String::from("/// The whole rulebook, in its order.\npub static BOOK: &[Entry] = &[\n");
    for chapter in &chapters {
        emit_module(
            &chapter.root,
            &chapter.key,
            0,
            &values,
            &mut rust,
            &mut errors,
        );
        emit_book(
            &chapter.root,
            &chapter.key,
            0,
            &values,
            &mut book,
            &mut errors,
        );
    }
    book.push_str("];\n");
    if !errors.is_empty() {
        panic!("the rulebook:\n  {}", errors.join("\n  "));
    }
    rust.push_str(&book);
    let (changes, table_files) = read_tables(&root.join("tables"))
        .unwrap_or_else(|error| panic!("the rulebook's tables: {error}"));
    rust.push_str(&changes);
    files.extend(table_files);
    let _ = writeln!(rust, "\n/// A digest of the rulebook's text: its edition.");
    let _ = writeln!(rust, "pub const EDITION: u64 = {:#018x};", edition(&files));
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("book.rs");
    std::fs::write(out, rust).expect("the generated rulebook");
}

/// `tables/<game>/<table>.toml`: changes to a game's own 2DA, as
/// `TABLE_CHANGES` (their order: game, table, then the file's). A file is
/// an optional `[table]` (`summary`) and a table per row (its label, as the
/// row's `label` cell has it, or its number), each key a column and its new
/// cell (a string or a number, written as is), and `why` (required).
fn read_tables(dir: &Path) -> Result<(String, Vec<PathBuf>), String> {
    let mut out = String::from(
        "\n/// The rulebook's changes to the games' own tables (`data/rules/tables/`).\npub static TABLE_CHANGES: &[TableChange] = &[\n",
    );
    let mut summaries = String::from(
        "\n/// What each changed table's file says of its changes: game, table, summary.\npub static TABLE_SUMMARIES: &[(&str, &str, &str)] = &[\n",
    );
    let mut files = Vec::new();
    let mut games: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|entries| {
            entries
                .flatten()
                .map(|entry| entry.path())
                .filter(|p| p.is_dir())
                .collect()
        })
        .unwrap_or_else(|_| Vec::new());
    games.sort();
    for game_dir in games {
        let game = game_dir
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("")
            .to_string();
        if !["k1", "tsl"].contains(&game.as_str()) {
            return Err(format!("{}: a game is `k1` or `tsl`", game_dir.display()));
        }
        let mut tables: Vec<PathBuf> = std::fs::read_dir(&game_dir)
            .map_err(|error| format!("{}: {error}", game_dir.display()))?
            .flatten()
            .map(|entry| entry.path())
            .filter(|path| path.extension().is_some_and(|ext| ext == "toml"))
            .collect();
        tables.sort();
        for path in tables {
            println!("cargo:rerun-if-changed={}", path.display());
            let at = path.display().to_string();
            let table = path
                .file_stem()
                .and_then(|n| n.to_str())
                .unwrap_or("")
                .to_ascii_lowercase();
            let source =
                std::fs::read_to_string(&path).map_err(|error| format!("{at}: {error}"))?;
            let doc = Document::parse(source.as_str()).map_err(|error| format!("{at}: {error}"))?;
            for (row, item) in doc.as_table().iter() {
                let cells = item
                    .as_table()
                    .ok_or_else(|| format!("{at}: `{row}` is not a table"))?;
                if row == "table" {
                    let summary = text(cells, "summary")
                        .map_err(|e| format!("{at}: {e}"))?
                        .unwrap_or_else(String::new);
                    let _ = writeln!(summaries, "    ({game:?}, {table:?}, {summary:?}),");
                    continue;
                }
                if cells.iter().all(|(column, _)| column == "why") {
                    return Err(format!("{at}: `[{row}]` changes no cell"));
                }
                let why = text(cells, "why")
                    .map_err(|e| format!("{at}: {e}"))?
                    .ok_or_else(|| format!("{at}: `[{row}]` says no `why`"))?;
                for (column, cell) in cells.iter() {
                    if column == "why" {
                        continue;
                    }
                    let value = cell
                        .as_value()
                        .and_then(|value| match value {
                            Value::String(text) => Some(text.value().to_string()),
                            Value::Integer(_) | Value::Float(_) => value
                                .span()
                                .and_then(|span| source.get(span))
                                .map(|raw| raw.trim().replace('_', "")),
                            _ => None,
                        })
                        .ok_or_else(|| {
                            format!("{at}: `[{row}] {column}` is not a string or a number")
                        })?;
                    let _ = writeln!(
                        out,
                        "    TableChange {{ game: {game:?}, table: {table:?}, row: {row:?}, column: {column:?}, value: {value:?}, why: {why:?} }},",
                    );
                }
            }
            files.push(path);
        }
    }
    out.push_str("];\n");
    summaries.push_str("];\n");
    out.push_str(&summaries);
    Ok((out, files))
}

struct Chapter {
    key: String,
    order: i64,
    root: Node,
}

/// A section (with its children) or a rule.
struct Node {
    key: String,
    title: String,
    summary: String,
    detail: String,
    rule: Option<Rule>,
    applies: Vec<String>,
    children: Vec<Node>,
}

struct Rule {
    ty: String,
    /// Each element's literal as the book writes it.
    literals: Vec<String>,
    array: bool,
    unit: String,
    labels: Vec<String>,
    source: String,
    see: String,
}

fn read_chapter(key: &str, doc: &Table, src: &str) -> Result<Chapter, String> {
    let head = doc
        .get("chapter")
        .and_then(Item::as_table)
        .ok_or("no [chapter] table")?;
    let order = head
        .get("order")
        .and_then(Item::as_integer)
        .ok_or("[chapter] has no integer `order`")?;
    for (name, _) in head.iter() {
        if !["title", "order", "summary", "detail"].contains(&name) {
            return Err(format!("[chapter] has an unknown key `{name}`"));
        }
    }
    let mut root = Node {
        key: key.to_string(),
        title: text(head, "title")?.ok_or("[chapter] has no title")?,
        summary: text(head, "summary")?.ok_or("[chapter] has no summary")?,
        detail: text(head, "detail")?.unwrap_or_else(String::new),
        rule: None,
        applies: Vec::new(),
        children: Vec::new(),
    };
    for (name, item) in doc.iter() {
        if name == "chapter" {
            continue;
        }
        let table = item
            .as_table()
            .ok_or_else(|| format!("`{name}` at the top is not a table"))?;
        root.children
            .push(read_node(name, table, &format!("{key}.{name}"), src)?);
    }
    Ok(Chapter {
        key: key.to_string(),
        order,
        root,
    })
}

fn read_node(key: &str, table: &Table, path: &str, src: &str) -> Result<Node, String> {
    check_key(key, path)?;
    let words = || key.replace('_', " ");
    if table.contains_key("value") {
        for (name, _) in table.iter() {
            if !RULE_KEYS.contains(&name) {
                return Err(format!("{path}: unknown key `{name}`"));
            }
        }
        let summary = text(table, "summary")?.ok_or_else(|| format!("{path}: no summary"))?;
        return Ok(Node {
            key: key.to_string(),
            title: text(table, "name")?.unwrap_or_else(|| capitalised(&words())),
            summary,
            detail: text(table, "detail")?.unwrap_or_else(String::new),
            rule: Some(read_rule(table, path, src)?),
            applies: applies(table, path)?,
            children: Vec::new(),
        });
    }
    let mut node = Node {
        key: key.to_string(),
        title: text(table, "title")?.unwrap_or_else(|| capitalised(&words())),
        summary: text(table, "summary")?.unwrap_or_else(String::new),
        detail: text(table, "detail")?.unwrap_or_else(String::new),
        rule: None,
        applies: applies(table, path)?,
        children: Vec::new(),
    };
    for (name, item) in table.iter() {
        if SECTION_KEYS.contains(&name) {
            continue;
        }
        let child = item
            .as_table()
            .ok_or_else(|| format!("{path}: `{name}` is neither a table nor a section's text"))?;
        node.children
            .push(read_node(name, child, &format!("{path}.{name}"), src)?);
    }
    Ok(node)
}

fn read_rule(table: &Table, path: &str, src: &str) -> Result<Rule, String> {
    let value = table["value"]
        .as_value()
        .ok_or_else(|| format!("{path}: `value` is not a value"))?;
    let (elements, array): (Vec<&Value>, bool) = match value {
        Value::Array(items) if items.is_empty() => {
            return Err(format!("{path}: an empty array"));
        }
        Value::Array(items) => (items.iter().collect(), true),
        other => (vec![other], false),
    };
    let first = elements[0];
    let ty = match text(table, "type")? {
        Some(ty) => ty,
        None if first.is_float() => "f32".to_string(),
        None if first.is_integer() => "i32".to_string(),
        None if first.is_bool() => "bool".to_string(),
        None => return Err(format!("{path}: a value of no known type")),
    };
    let range = match table.get("range") {
        None => None,
        Some(item) => {
            let bounds = item
                .as_array()
                .filter(|bounds| bounds.len() == 2)
                .ok_or_else(|| format!("{path}: `range` is not [least, most]"))?;
            let bound = |at: usize| {
                let bound = bounds.get(at).expect("two bounds");
                bound
                    .as_float()
                    .or_else(|| bound.as_integer().map(|i| i as f64))
                    .ok_or_else(|| format!("{path}: a range bound is not a number"))
            };
            Some((bound(0)?, bound(1)?))
        }
    };
    let mut literals = Vec::new();
    for element in elements {
        literals.push(literal(element, &ty, range, path, src)?);
    }
    let labels = match table.get("labels") {
        None => Vec::new(),
        Some(item) => {
            let labels: Option<Vec<String>> = item
                .as_array()
                .map(|labels| {
                    labels
                        .iter()
                        .map(|l| l.as_str().map(str::to_string))
                        .collect()
                })
                .and_then(|labels: Vec<Option<String>>| labels.into_iter().collect());
            let labels = labels.ok_or_else(|| format!("{path}: `labels` are not strings"))?;
            if !array || labels.len() != literals.len() {
                return Err(format!("{path}: one label for each of the array's values"));
            }
            labels
        }
    };
    Ok(Rule {
        ty,
        literals,
        array,
        unit: text(table, "unit")?.unwrap_or_else(String::new),
        labels,
        source: text(table, "source")?.unwrap_or_else(String::new),
        see: text(table, "see")?.unwrap_or_else(String::new),
    })
}

/// The Rust literal for one element, checked against its type and range.
fn literal(
    value: &Value,
    ty: &str,
    range: Option<(f64, f64)>,
    path: &str,
    src: &str,
) -> Result<String, String> {
    // The number as the book writes it, so a float is the same literal the
    // code had (its f32 rounded from the same decimal).
    let raw = |value: &Value| {
        value
            .span()
            .and_then(|span| src.get(span))
            .map(|text| text.trim().to_string())
            .unwrap_or_else(String::new)
    };
    let number = if INTEGERS.contains(&ty) {
        let int = value
            .as_integer()
            .ok_or_else(|| format!("{path}: `{ty}` wants whole numbers"))?;
        let (least, most): (i128, i128) = match ty {
            "i8" => (i8::MIN.into(), i8::MAX.into()),
            "i16" => (i16::MIN.into(), i16::MAX.into()),
            "i32" => (i32::MIN.into(), i32::MAX.into()),
            "u8" => (0, u8::MAX.into()),
            "u16" => (0, u16::MAX.into()),
            "u32" => (0, u32::MAX.into()),
            "u64" | "usize" => (0, i64::MAX.into()),
            _ => (i64::MIN.into(), i64::MAX.into()),
        };
        if !(least..=most).contains(&i128::from(int)) {
            return Err(format!("{path}: {int} does not fit `{ty}`"));
        }
        int as f64
    } else if FLOATS.contains(&ty) {
        value
            .as_float()
            .or_else(|| value.as_integer().map(|i| i as f64))
            .ok_or_else(|| format!("{path}: `{ty}` wants numbers"))?
    } else if ty == "bool" {
        let flag = value
            .as_bool()
            .ok_or_else(|| format!("{path}: `bool` wants true or false"))?;
        return Ok(flag.to_string());
    } else {
        return Err(format!("{path}: unknown type `{ty}`"));
    };
    if let Some((least, most)) = range
        && !(least..=most).contains(&number)
    {
        return Err(format!(
            "{path}: {number} is outside its range [{least}, {most}]"
        ));
    }
    let mut text = raw(value);
    if FLOATS.contains(&ty) && value.is_integer() {
        text.push_str(".0");
    }
    Ok(text)
}

/// A table's `applies` tags, each `what:label` with a known `what`.
fn applies(table: &Table, path: &str) -> Result<Vec<String>, String> {
    let Some(item) = table.get("applies") else {
        return Ok(Vec::new());
    };
    let tags = item
        .as_array()
        .ok_or_else(|| format!("{path}: `applies` is not an array"))?;
    let mut out = Vec::new();
    for tag in tags {
        let tag = tag
            .as_str()
            .ok_or_else(|| format!("{path}: an `applies` tag is not a string"))?;
        match tag.split_once(':') {
            Some((what, label)) if APPLIES.contains(&what) && !label.is_empty() => {
                out.push(tag.to_string());
            }
            _ => {
                return Err(format!(
                    "{path}: `{tag}` is not `what:label` with what one of {APPLIES:?}"
                ));
            }
        }
    }
    Ok(out)
}

fn text(table: &Table, key: &str) -> Result<Option<String>, String> {
    match table.get(key) {
        None => Ok(None),
        Some(item) => item
            .as_str()
            .map(|s| Some(s.trim().to_string()))
            .ok_or_else(|| format!("`{key}` is not a string")),
    }
}

fn check_key(key: &str, path: &str) -> Result<(), String> {
    let good = key.starts_with(|c: char| c.is_ascii_lowercase())
        && key
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if good {
        Ok(())
    } else {
        Err(format!("{path}: keys are snake_case"))
    }
}

fn capitalised(words: &str) -> String {
    let mut chars = words.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

/// Every rule's displayed value by its place, for the prose's names.
fn values(chapters: &[Chapter]) -> BTreeMap<String, (Vec<String>, String)> {
    fn walk(node: &Node, path: &str, out: &mut BTreeMap<String, (Vec<String>, String)>) {
        if let Some(rule) = &node.rule {
            let shown = rule.literals.iter().map(|l| shown::literal(l)).collect();
            out.insert(path.to_string(), (shown, rule.unit.clone()));
        }
        for child in &node.children {
            walk(child, &format!("{path}.{}", child.key), out);
        }
    }
    let mut out = BTreeMap::new();
    for chapter in chapters {
        walk(&chapter.root, &chapter.key, &mut out);
    }
    out
}

/// Prose with every `{name}` replaced by its value.
fn render(
    prose: &str,
    at: &str,
    values: &BTreeMap<String, (Vec<String>, String)>,
    errors: &mut Vec<String>,
) -> String {
    let mut out = String::new();
    let mut rest = prose;
    while let Some(open) = rest.find(['{', '}']) {
        out.push_str(&rest[..open]);
        let tail = &rest[open..];
        if tail.starts_with("{{") || tail.starts_with("}}") {
            out.push_str(&tail[..1]);
            rest = &tail[2..];
            continue;
        }
        if let Some(after) = tail.strip_prefix('}') {
            errors.push(format!("{at}: a lone `}}` (write `}}}}`)"));
            rest = after;
            continue;
        }
        let Some(close) = tail.find('}') else {
            errors.push(format!("{at}: an unclosed `{{`"));
            rest = "";
            break;
        };
        let name = &tail[1..close];
        rest = &tail[close + 1..];
        let (name, how) = match name.rsplit_once(':') {
            Some((name, how)) if ["bare", "m", "s", "pct", "fp", "can"].contains(&how) => {
                (name, Some(how))
            }
            Some(_) => {
                errors.push(format!(
                    "{at}: `{{{name}}}`: a modifier is :bare, :m, :s, :pct, :fp or :can"
                ));
                continue;
            }
            None => (name, None),
        };
        let (name, index) = match name.split_once('[') {
            Some((name, index)) => {
                match index
                    .strip_suffix(']')
                    .and_then(|i| i.parse::<usize>().ok())
                {
                    Some(index) => (name, Some(index)),
                    None => {
                        errors.push(format!("{at}: `{{{name}[{index}}}` is no entry's number"));
                        continue;
                    }
                }
            }
            None => (name, None),
        };
        let Some((shown, unit)) = values.get(name) else {
            errors.push(format!("{at}: `{{{name}}}` names no rule"));
            continue;
        };
        let values: Vec<&String> = match index {
            Some(index) => match shown.get(index) {
                Some(value) => vec![value],
                None => {
                    errors.push(format!("{at}: `{name}` has no entry {index}"));
                    continue;
                }
            },
            None => shown.iter().collect(),
        };
        let said: Result<Vec<String>, String> = values
            .iter()
            .map(|value| match how {
                Some("bare") => Ok(value.to_string()),
                Some(how) => shown::spoken(value, unit, how),
                None => Ok(with_unit(value, unit)),
            })
            .collect();
        match said {
            Ok(said) => out.push_str(&said.join(" / ")),
            Err(error) => errors.push(format!("{at}: `{{{name}}}`: {error}")),
        }
    }
    out.push_str(rest);
    out
}

fn doc_comment(out: &mut String, indent: &str, texts: &[&str]) {
    let mut first = true;
    for text in texts.iter().filter(|t| !t.is_empty()) {
        if !first {
            let _ = writeln!(out, "{indent}///");
        }
        first = false;
        // Each paragraph one line: a wrapped line that starts with a number
        // or a dash would read to rustdoc as a list.
        for (at, paragraph) in text.split("\n\n").enumerate() {
            if at > 0 {
                let _ = writeln!(out, "{indent}///");
            }
            let line = paragraph.split_whitespace().collect::<Vec<_>>().join(" ");
            let _ = writeln!(
                out,
                "{indent}/// {}",
                line.replace('[', "\\[").replace(']', "\\]")
            );
        }
    }
}

fn emit_module(
    node: &Node,
    path: &str,
    depth: usize,
    values: &BTreeMap<String, (Vec<String>, String)>,
    out: &mut String,
    errors: &mut Vec<String>,
) {
    let indent = "    ".repeat(depth);
    let summary = render(&node.summary, path, values, errors);
    if let Some(rule) = &node.rule {
        doc_comment(out, &indent, &[&summary]);
        let name = node.key.to_uppercase();
        let ty = &rule.ty;
        if rule.array {
            let n = rule.literals.len();
            let items: Vec<String> = rule.literals.iter().map(|l| typed(l, ty)).collect();
            let _ = writeln!(
                out,
                "{indent}pub const {name}: [{ty}; {n}] = [{}];",
                items.join(", ")
            );
        } else {
            let _ = writeln!(
                out,
                "{indent}pub const {name}: {ty} = {};",
                typed(&rule.literals[0], ty)
            );
        }
        return;
    }
    doc_comment(out, &indent, &[&node.title, &summary]);
    let _ = writeln!(out, "{indent}pub mod {} {{", node.key);
    let mut names = BTreeSet::new();
    for child in &node.children {
        if !names.insert(child.key.clone()) {
            errors.push(format!("{path}.{}: twice", child.key));
        }
        emit_module(
            child,
            &format!("{path}.{}", child.key),
            depth + 1,
            values,
            out,
            errors,
        );
    }
    let _ = writeln!(out, "{indent}}}");
}

fn typed(literal: &str, ty: &str) -> String {
    if ty == "bool" {
        literal.to_string()
    } else {
        format!("{literal}_{ty}")
    }
}

fn emit_book(
    node: &Node,
    path: &str,
    depth: usize,
    values: &BTreeMap<String, (Vec<String>, String)>,
    out: &mut String,
    errors: &mut Vec<String>,
) {
    // A rule's summary says its own value, so every page quoting the
    // summary alone (the game's descriptions) says the number it plays.
    if node.rule.is_some() && !node.summary.contains(&format!("{{{path}")) {
        errors.push(format!(
            "{path}: its summary does not say its value (`{{{path}}}`)"
        ));
    }
    let summary = render(&node.summary, path, values, errors);
    let detail = render(&node.detail, path, values, errors);
    let (values_shown, kind) = match &node.rule {
        Some(rule) => {
            let shown: Vec<String> = rule
                .literals
                .iter()
                .map(|l| format!("{:?}", shown::literal(l)))
                .collect();
            let labels: Vec<String> = rule.labels.iter().map(|l| format!("{l:?}")).collect();
            (
                format!("&[{}]", shown.join(", ")),
                format!(
                    "Kind::Rule {{ ty: {:?}, array: {}, unit: {:?}, labels: &[{}], source: {:?}, see: {:?}, constant: {:?} }}",
                    rule.ty,
                    rule.array,
                    rule.unit,
                    labels.join(", "),
                    rule.source,
                    rule.see,
                    format!(
                        "rules::{}::{}",
                        parent(path).replace('.', "::"),
                        node.key.to_uppercase()
                    ),
                ),
            )
        }
        None => ("&[]".to_string(), "Kind::Section".to_string()),
    };
    let _ = writeln!(
        out,
        "    Entry {{ path: {path:?}, depth: {depth}, title: {:?}, summary: {summary:?}, detail: {detail:?}, values: {values_shown}, applies: &{:?}, kind: {kind} }},",
        node.title, node.applies,
    );
    for child in &node.children {
        emit_book(
            child,
            &format!("{path}.{}", child.key),
            depth + 1,
            values,
            out,
            errors,
        );
    }
}

fn parent(path: &str) -> &str {
    path.rsplit_once('.').map_or("", |(parent, _)| parent)
}

/// FNV-1a over the files' names and text.
fn edition(files: &[PathBuf]) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for path in files {
        let name = path
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_else(String::new);
        let text = std::fs::read(path).unwrap_or_else(|_| Vec::new());
        for byte in name.bytes().chain(text) {
            hash ^= u64::from(byte);
            hash = hash.wrapping_mul(0x0100_0000_01b3);
        }
    }
    hash
}
